    public function run(): void
    {
        AuditLog::withoutRecording(function (): void {
            RegulatoryDocument::withTrashed()->forceDelete();

            $now = now();
            $payload = [];

            foreach (self::records() as $row) {
                $payload[] = $this->buildRow('فحص دوري', $row, null, $now);
            }

            foreach (self::operatingCardRecords() as $row) {
                $payload[] = $this->buildRow('كرت تشغيل', $row, $row[8], $now);
            }

            foreach (self::registrationRecords() as $row) {
                $payload[] = $this->buildRow('استمارة', $row, $row[8], $now);
            }

            foreach (array_chunk($payload, 50) as $chunk) {
                RegulatoryDocument::query()->insert($chunk);
            }
        });

        DashboardService::clearCache();
    }

    /**
     * @param  array<int, ?string>  $row
     * @return array<string, mixed>
     */
    private function buildRow(string $documentType, array $row, ?string $renewalStatus, mixed $now): array
    {
        return [
            'entity_type' => RegulatoryEntityType::Equipment->value,
            'entity_identifier' => $row[0],
            'equipment_type' => $row[1],
            'plate_number' => $row[2],
            'transport_type' => $row[3],
            'branch' => $row[4],
            'document_type' => $documentType,
            'document_number' => $row[5],
            'issue_date' => null,
            'hijri_expiry_date' => $row[6],
            'expiry_date' => $row[7],
            'compliance_status' => ComplianceStatus::Expired->value,
            'renewal_status' => $renewalStatus,
            'renewal_cost' => 0,
            'notes' => null,
            'created_at' => $now,
            'updated_at' => $now,
        ];
    }
